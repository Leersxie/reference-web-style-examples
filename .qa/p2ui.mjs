import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: 'C://Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true })
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', e => errors.push(e.message))
await page.goto('http://127.0.0.1:5178/?p2=3#/channel/arena', { waitUntil: 'networkidle' })
await page.waitForTimeout(700)
await page.getByRole('button', { name: '频道参数' }).click()
await page.waitForTimeout(450)
await page.screenshot({ path: '.shots/p2-drawer.png' })
await page.keyboard.press('Escape')
await page.waitForTimeout(400)
await page.getByRole('button', { name: '预约观赛' }).click()
await page.waitForTimeout(450)
await page.screenshot({ path: '.shots/p2-modal.png' })
await page.keyboard.press('Escape')
await page.waitForTimeout(400)
await page.getByRole('button', { name: '打开界面设置' }).click()
await page.waitForTimeout(450)
await page.screenshot({ path: '.shots/p2-settings.png' })
await page.keyboard.press('Escape')
await page.waitForTimeout(300)
// transition mid-frame
await page.goto('http://127.0.0.1:5178/?p2=4#/', { waitUntil: 'networkidle' })
await page.waitForTimeout(700)
await page.getByRole('button', { name: /进入争锋频道/ }).click()
await page.waitForTimeout(380)
await page.screenshot({ path: '.shots/p2-mask.png' })
console.log('errors', errors.slice(0,4))
await browser.close()
