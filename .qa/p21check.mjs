import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: 'C://Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true })
const errors = []
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1100 } })
const page = await ctx.newPage()
page.on('pageerror', e => errors.push(e.message))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto('http://127.0.0.1:5178/?p21=1#/', { waitUntil: 'networkidle' })
await page.waitForTimeout(1100)
await page.screenshot({ path: '.shots/p21-home.png' })
await page.goto('http://127.0.0.1:5178/?p21=2#/lab', { waitUntil: 'networkidle' })
await page.waitForTimeout(500)
await page.getByRole('button', { name: /转场实验/ }).click()
await page.waitForTimeout(500)
await page.screenshot({ path: '.shots/p21-lab-motion.png' })
await page.getByRole('button', { name: /组件状态/ }).click()
await page.waitForTimeout(400)
await page.screenshot({ path: '.shots/p21-lab-comp.png', fullPage: true })
await page.goto('http://127.0.0.1:5178/?p21=3#/terminal', { waitUntil: 'networkidle' })
await page.waitForTimeout(600)
await page.screenshot({ path: '.shots/p21-terminal.png' })
await page.goto('http://127.0.0.1:5178/?p21=4#/channel/arena', { waitUntil: 'networkidle' })
await page.waitForTimeout(600)
await page.getByRole('tab', { name: /赛程/ }).click()
await page.waitForTimeout(400)
await page.getByRole('tab', { name: /总览/ }).click()
await page.waitForTimeout(300)
await page.screenshot({ path: '.shots/p21-detail.png' })
console.log('errors', errors.slice(0,5))

const ctx2 = await browser.newContext({ viewport: { width: 360, height: 800 } })
const p2 = await ctx2.newPage()
for (const [n,u] of [['home','#/'],['terminal','#/terminal'],['detail','#/channel/arena']]) {
  await p2.goto('http://127.0.0.1:5178/?p21m=' + n + u, { waitUntil: 'networkidle' })
  await p2.waitForTimeout(600)
  await p2.screenshot({ path: `.shots/p21-360-${n}.png`, fullPage: n === 'detail' })
}
console.log('360 width', await p2.evaluate(() => [document.documentElement.scrollWidth, document.documentElement.clientWidth]))
await browser.close()
