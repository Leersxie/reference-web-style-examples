import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: 'C://Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true })
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
const page = await ctx.newPage()
await page.goto('http://127.0.0.1:5178/?s2=1#/channels', { waitUntil: 'networkidle' })
await page.waitForTimeout(800)
await page.getByRole('button', { name: '选择转场类型' }).click()
await page.getByRole('option', { name: '纸面翻页' }).click()
await page.getByRole('button', { name: /争锋频道/ }).first().click()
await page.waitForTimeout(200)
await page.screenshot({ path: '.shots/p22-tx-sheet.png' })
await page.waitForTimeout(1400)
console.log('done', await page.evaluate(() => location.hash))
await browser.close()
