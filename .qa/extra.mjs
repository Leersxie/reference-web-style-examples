import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: 'C://Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true })
const m = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
const mp = await m.newPage()
await mp.goto('http://127.0.0.1:5178/#/', { waitUntil: 'networkidle' })
await mp.waitForTimeout(500)
await mp.getByRole('button', { name: '打开导航' }).click()
await mp.waitForTimeout(400)
console.log('mobnav open', await mp.locator('.hc-mobnav').count(), 'focus inside', await mp.evaluate(() => !!document.activeElement?.closest('.hc-mobnav')))
await mp.screenshot({ path: '.shots/mobnav.png' })
await mp.keyboard.press('Escape')
await mp.waitForTimeout(400)
console.log('mobnav closed', await mp.locator('.hc-mobnav').count(), 'overflow', await mp.evaluate(()=>document.body.style.overflow))

const d = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
const dp = await d.newPage()
await dp.goto('http://127.0.0.1:5178/#/lab', { waitUntil: 'networkidle' })
await dp.waitForTimeout(500)
await dp.getByRole('button', { name: '打开界面设置' }).click()
await dp.waitForTimeout(450)
console.log('settings drawer', await dp.locator('.hc-drawer').count())
await dp.getByRole('button', { name: '2×' }).click()
await dp.waitForTimeout(200)
console.log('lab meta shows speed', await dp.getByText(/SPEED 2×/).count())
await dp.screenshot({ path: '.shots/settings.png' })
await browser.close()
