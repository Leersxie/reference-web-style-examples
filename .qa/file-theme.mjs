import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: 'C://Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true })
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
const page = await ctx.newPage()
const errs = []
page.on('pageerror', e => errs.push(e.message))
await page.goto('file:///H:/Workbuddy%20cangku/mrfz/honey-city.html#/', { waitUntil: 'load' })
await page.waitForTimeout(700)
await page.getByRole('button', { name: '打开界面设置' }).click()
await page.waitForTimeout(300)
await page.getByRole('button', { name: '档案纸面' }).click()
await page.waitForTimeout(300)
const theme1 = await page.evaluate(() => document.documentElement.dataset.theme)
const ls = await page.evaluate(() => { try { return localStorage.getItem('honeycity.prefs.v1') } catch (e) { return 'ERR:' + e.name } })
await page.reload({ waitUntil: 'load' })
await page.waitForTimeout(700)
const theme2 = await page.evaluate(() => document.documentElement.dataset.theme)
console.log({ theme1, ls, theme2, errs })
await browser.close()
